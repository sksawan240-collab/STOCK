import PDFDocument from 'pdfkit';

export async function generatePdfReportBuffer(analysis: any, user: any): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const buffers: Buffer[] = [];

      doc.on('data', (chunk) => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', (err) => reject(err));

      // Header Branding
      doc.fontSize(22).fillColor('#1e3a8a').text('AI StockVision', { align: 'left' });
      doc.fontSize(12).fillColor('#64748b').text('Intelligent Stock Chart Analysis & Educational Report', { align: 'left' });
      doc.moveDown(1);

      // Report metadata box
      doc.rect(50, doc.y, 495, 60).fillAndStroke('#f1f5f9', '#cbd5e1');
      const startY = doc.y + 10;
      doc.fontSize(10).fillColor('#334155');
      doc.text(`Stock Symbol: ${analysis.stockSymbol} (${analysis.exchange})`, 65, startY);
      doc.text(`Timeframe: ${analysis.timeframe}`, 320, startY);
      doc.text(`Reference Price: ₹${analysis.referencePrice}`, 65, startY + 20);
      doc.text(`Generated For: ${user.name} (${user.email})`, 320, startY + 20);
      doc.text(`Date: ${new Date(analysis.createdAt || Date.now()).toLocaleString()}`, 65, startY + 40);
      doc.moveDown(3);

      // Section 1: Technical Indicators
      doc.fontSize(14).fillColor('#0f172a').text('1. Technical Indicator Summary');
      doc.fontSize(10).fillColor('#334155');
      doc.text(`• RSI (14): ${analysis.technicalIndicators?.rsi || 'N/A'}`);
      doc.text(`• MACD: ${analysis.technicalIndicators?.macd || 'N/A'}`);
      doc.text(`• 50 SMA: ${analysis.technicalIndicators?.sma50 || 'N/A'}`);
      doc.text(`• 200 SMA: ${analysis.technicalIndicators?.sma200 || 'N/A'}`);
      doc.text(`• Bollinger Bands: ${analysis.technicalIndicators?.bollingerBands || 'N/A'}`);
      doc.moveDown(1);

      // Section 2: Support & Resistance
      doc.fontSize(14).fillColor('#0f172a').text('2. Key Support & Resistance Levels');
      doc.fontSize(10).fillColor('#334155');
      doc.text(`• Support Levels: ${(analysis.supportLevels || []).join(', ')}`);
      doc.text(`• Resistance Levels: ${(analysis.resistanceLevels || []).join(', ')}`);
      doc.moveDown(1);

      // Section 3: Forecast Scenarios
      doc.fontSize(14).fillColor('#0f172a').text('3. AI Price Scenarios');
      doc.fontSize(10).fillColor('#334155');
      doc.text(`• Bullish Target: ₹${analysis.forecastScenarios?.bullish?.target || 'N/A'} — ${analysis.forecastScenarios?.bullish?.description || ''}`);
      doc.text(`• Bearish Target: ₹${analysis.forecastScenarios?.bearish?.target || 'N/A'} — ${analysis.forecastScenarios?.bearish?.description || ''}`);
      doc.text(`• Neutral Scenario: ₹${analysis.forecastScenarios?.neutral?.target || 'N/A'} — ${analysis.forecastScenarios?.neutral?.description || ''}`);
      doc.moveDown(1);

      // Section 4: Risk Assessment
      doc.fontSize(14).fillColor('#0f172a').text('4. Risk Management & Stop-Loss');
      doc.fontSize(10).fillColor('#334155');
      doc.text(`• Stop Loss Reference: ₹${analysis.riskAssessment?.stopLoss || 'N/A'}`);
      doc.text(`• Risk-to-Reward Ratio: ${analysis.riskAssessment?.riskRewardRatio || 'N/A'}`);
      doc.text(`• Market Volatility: ${analysis.riskAssessment?.volatility || 'N/A'}`);
      doc.text(`• Max Recommended Capital Risk: ${analysis.riskAssessment?.maxRecommendedRiskPct || 2}%`);
      doc.moveDown(2);

      // Mandatory Disclaimer (Page footer or bottom box)
      doc.addPage();
      doc.fontSize(12).fillColor('#b91c1c').text('MANDATORY EDUCATIONAL & SEBI REGULATORY DISCLAIMER', { align: 'center' });
      doc.moveDown(0.5);
      doc.fontSize(8.5).fillColor('#475569').text(
        'EDUCATIONAL PURPOSES ONLY — NOT INVESTMENT ADVICE.\n\n' +
        'This report is generated by AI StockVision, an AI-assisted educational stock-market analysis platform. It is intended solely for learning, research, and demonstration of technical analysis concepts.\n\n' +
        'The analysis, forecasts, chart markings, price scenarios, and risk calculations are uncertain and may be incomplete, inaccurate, or based on limited historical information. They do not guarantee future market performance.\n\n' +
        'This report is not a recommendation, solicitation, or offer to buy, sell, or hold any security or financial instrument. It is not personalized investment advice, and it should not be relied upon as the sole basis for any financial decision.\n\n' +
        'SEBI AND REGULATORY COMPLIANCE NOTICE: This educational report does not claim to be approved, endorsed, certified, or authorized by the Securities and Exchange Board of India (SEBI). The website operator must ensure that the platform\'s actual services, communications, and business model comply with applicable Indian securities laws and SEBI requirements. This disclaimer does not exempt any person or business from applicable registration, licensing, disclosure, or other legal obligations.\n\n' +
        'Stock prices can change rapidly. Past performance does not guarantee future results. Forecasts may be wrong. Stop-loss levels may not execute at the expected price, and actual losses can exceed calculated estimates.\n\n' +
        'Users should independently verify market data and consult a suitably qualified and appropriately registered professional where required before making financial decisions.\n\n' +
        'Report ID: ' + (analysis._id || 'SV-' + Date.now()) + ' | Generated by AI StockVision Educational Platform',
        { align: 'justify' }
      );

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
